    private void btnListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarActionPerformed
        PessoasController pc = new PessoasController();
        ArrayList<Pessoa> resultados = new ArrayList<>();
        resultados = pc.buscarDados();

        DefaultTableModel dtm = (DefaultTableModel) tblPessoas.getModel();
        
        int l = tblPessoas.getRowCount();
        for (int i = l - 1; i >= 0; --i) {
            dtm.removeRow(i);
        }

        for (int i = resultados.size() - 1; i >=0; i--) {
            int id = resultados.get(i).getId();
            String nome = resultados.get(i).getNome();
            double salario = resultados.get(i).getSalario();
            dtm.addRow(new Object[]{id, nome, salario});
        }
    }//GEN-LAST:event_btnListarActionPerformed

